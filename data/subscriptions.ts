export function findSubscription(id: string): Subscription | undefined {
  if (!id) return undefined;

  // 1. Direct match
  const direct = subscriptions.find((s) => s.id === id);
  if (direct) return direct;

  // 2. Exact match with common region suffixes
  const withSuffix = subscriptions.find(
    (s) =>
      s.id === `${id}-global` ||
      s.id === `${id}-us` ||
      s.id === `${id}-jp` ||
      s.id === `${id}-id`
  );
  if (withSuffix) return withSuffix;

  // 3. Normalized ID match (e.g. "chatgpt" matches "chatgpt-plus-global")
  const normId = id.replace(/-(global|us|jp|id)$/i, "").toLowerCase();
  const normalizedMatch = subscriptions.find((s) => {
    const sNorm = s.id.replace(/-(global|us|jp|id)$/i, "").toLowerCase();
    return (
      sNorm === normId ||
      sNorm.startsWith(normId) ||
      normId.startsWith(sNorm)
    );
  });
  if (normalizedMatch) return normalizedMatch;

  // 4. Name match (case-insensitive)
  const nameMatch = subscriptions.find(
    (s) =>
      s.name.toLowerCase() === normId ||
      s.name.toLowerCase().includes(normId)
  );
  if (nameMatch) return nameMatch;

  return undefined;
}

